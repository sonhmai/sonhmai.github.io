import fs from 'node:fs';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
const base = process.env.PREVIEW_URL || 'http://127.0.0.1:4321';
fs.mkdirSync('.audit/screenshots',{recursive:true});
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
const noOverflow = async () => assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),`Horizontal page overflow at ${page.url()}`);
try {
  await page.goto(base);
  await page.getByRole('navigation').getByRole('link',{name:'Writing',exact:true}).click();
  await page.waitForURL('**/writing/');
  await expect(page.locator('main li')).toHaveCount(8);
  await page.getByRole('navigation').getByRole('link',{name:'Projects',exact:true}).click();
  await page.waitForURL('**/projects/');
  await expect(page.getByRole('link',{name:'Monix MDC example'})).toBeVisible();
  await page.getByRole('navigation').getByRole('link',{name:'About',exact:true}).click();
  await page.waitForURL('**/about/');
  await expect(page.locator('main')).toContainText('Vietnam');
  const originalTheme=await page.locator('html').getAttribute('data-theme');
  await page.locator('#theme-btn').click();
  const changedTheme=await page.locator('html').getAttribute('data-theme');
  assert.notEqual(changedTheme,originalTheme);
  await page.reload();
  assert.equal(await page.locator('html').getAttribute('data-theme'),changedTheme);
  await page.goto(base);
  await page.screenshot({path:'.audit/screenshots/desktop-dark.png',fullPage:true});
  await page.locator('#theme-btn').click();
  await page.screenshot({path:'.audit/screenshots/desktop-light.png',fullPage:true});
  await page.getByRole('navigation').getByRole('link',{name:'Search',exact:true}).click();
  await page.waitForURL('**/search/');
  const input=page.locator('.pagefind-ui__search-input');
  await input.fill('MVCC');
  await page.getByRole('link',{name:'Two Phase Commit Pattern',exact:true}).waitFor();
  await page.getByRole('link',{name:'Two Phase Commit Pattern',exact:true}).click();
  await page.waitForURL('**/TwoPhaseCommit/');
  assert(await page.getByRole('heading',{name:'Two Phase Commit Pattern',exact:true}).isVisible());
  await page.locator('.mermaid-diagram svg').first().waitFor();
  assert.equal(await page.locator('.mermaid-diagram svg').count(),3);
  assert.equal(await page.locator('.missing-figure').count(),5);
  assert(await page.locator('pre code').count()>0);
  assert.equal(await page.locator('link[rel=canonical]').getAttribute('href'),'https://sonhmai.github.io/TwoPhaseCommit/');
  await noOverflow();
  await page.screenshot({path:'.audit/screenshots/article.png',fullPage:true});
  const inventory=JSON.parse(fs.readFileSync('docs/migration-inventory.json','utf8'));
  for(const item of inventory.content.filter(item=>item.kind==='article'||item.kind==='paper-note')) {
    const response=await page.goto(`${base}${item.url}`);
    assert(response.ok(),`Article failed: ${item.url}`);
    for(const image of await page.locator('article img').all()) assert(await image.evaluate(img=>img.complete&&img.naturalWidth>0),`Broken image in ${item.url}`);
    await noOverflow();
  }
  const redirects=JSON.parse(fs.readFileSync('src/data/redirects.json','utf8'));
  const legacyUrls=[...new Set([...inventory.content.map(item=>item.url).filter(Boolean),...Object.keys(redirects)])].filter(url=>url!=='/feed.xml'&&url!=='/404.html');
  for(const url of legacyUrls) {
    const response=await page.goto(`${base}${url}`);
    assert(response.ok(),`Old URL failed: ${url}`);
    await page.waitForLoadState('networkidle');
    assert(!await page.getByRole('heading',{name:'404',exact:true}).count(),`Old URL became 404: ${url}`);
    let target=url;
    while(redirects[target]) target=redirects[target];
    await expect(page).toHaveURL(new RegExp(`${target.replace(/[.*+?^${}()|[\]\\]/g,'\\$&').replace(/\/$/,'')}/?$`));
  }
  const notFound=await page.goto(`${base}/missing-route-for-verification/`);
  assert.equal(notFound.status(),404);
  await expect(page.getByRole('heading',{name:'404',exact:true})).toBeVisible();
  const feed=await page.request.get(`${base}/feed.xml`);
  assert(feed.ok());assert((await feed.text()).includes('<rss'));
  assert(!await page.locator('script[src*="cloudflareinsights"]').count(),'Unexpected analytics without token');
  await page.setViewportSize({width:375,height:812});
  await page.goto(base);
  await noOverflow();
  await page.locator('#menu-btn').click();
  assert.equal(await page.locator('#menu-btn').getAttribute('aria-expanded'),'true');
  await page.getByRole('navigation').getByRole('link',{name:'Writing',exact:true}).click();
  await page.waitForURL('**/writing/');
  await noOverflow();
  await page.screenshot({path:'.audit/screenshots/mobile-writing.png',fullPage:true});
  await page.goto(`${base}/software/monix-async-and-mdc-in-scala`);
  await noOverflow();
  assert(await page.locator('pre').evaluateAll(blocks=>blocks.every(block=>getComputedStyle(block).overflowX==='auto')));
  await page.screenshot({path:'.audit/screenshots/mobile-code.png',fullPage:true});
  await page.goto(`${base}/TwoPhaseCommit/`);
  await page.locator('.mermaid-diagram svg').first().waitFor();
  await noOverflow();
  await page.screenshot({path:'.audit/screenshots/mobile-diagram.png',fullPage:true});
  assert.deepEqual(errors,[],'Browser JavaScript errors');
  console.log('PASS navigation, 8 articles and paper notes, search, theme persistence, mobile menu/layout, code scrolling, 3 Mermaid diagrams, legacy URLs, feed, and analytics absence.');
} finally { await browser.close(); }
